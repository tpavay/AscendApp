#!/usr/bin/env node

/**
 * Publishes drop email pictures under content-hashed names.
 *
 * A mailbox fetches a remote picture once and keeps it by address - Gmail
 * through its image proxy - so a picture changed after any email referenced
 * it keeps showing the old one under the same name. A staging test showed the
 * captain a hero picture that had already been replaced (2026-10-02). So no
 * drop picture is ever served under a hand-typed name: each source in
 * `web/drop-email-assets/<dropId>/` is copied to
 * `web/public/images/drops/<dropId>/<stem>-<hash>.<ext>`, where the hash is
 * the first 12 hex digits of the file's SHA-256, and the email code reads the
 * names from the generated `functions/src/email/dropAssets.generated.ts`.
 * A changed picture is a new name, so nothing can be served from a cache.
 *
 * Usage:
 *   node scripts/build-drop-email-assets.mjs           # write
 *   node scripts/build-drop-email-assets.mjs --check   # exit 1 if stale
 *
 * `--check` is what `scripts/test/drop-email-assets.test.mjs` runs, so a
 * picture added, edited or removed without rerunning this fails the suite.
 */

import {createHash} from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import {dirname, extname, join, resolve} from "node:path";
import {fileURLToPath} from "node:url";

import {isEntrypoint} from "./lib/is-entrypoint.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE_DIR = join(ROOT, "web/drop-email-assets");
export const PUBLIC_DIR = join(ROOT, "web/public/images/drops");
export const MANIFEST_PATH = join(
  ROOT,
  "functions/src/email/dropAssets.generated.ts"
);
const PICTURE = /\.(png|jpe?g|gif)$/i;

if (isEntrypoint(import.meta.url)) {
  const check = process.argv.includes("--check");
  const problems = check ? checkDropEmailAssets() : writeDropEmailAssets();
  for (const problem of problems) {
    console.error(problem);
  }
  if (check && problems.length > 0) {
    console.error("Run: node scripts/build-drop-email-assets.mjs");
    process.exitCode = 1;
  } else if (!check) {
    console.log(`Wrote ${MANIFEST_PATH}`);
  }
}

/**
 * The published name for one source picture.
 * @param {string} fileName Source file name, e.g. "pumpkin_ghost.png".
 * @param {Buffer} bytes The file's contents.
 * @return {string} e.g. "pumpkin_ghost-0123456789ab.png".
 */
export function hashedName(fileName, bytes) {
  const extension = extname(fileName);
  const stem = fileName.slice(0, -extension.length);
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
  return `${stem}-${hash}${extension}`;
}

/**
 * What the sources say should be published: per drop, each source name
 * mapped to its site-relative hashed path, plus the bytes behind it.
 * @return {Array<{dropId: string, source: string, path: string, bytes: Buffer}>}
 */
export function plannedAssets() {
  if (!existsSync(SOURCE_DIR)) {
    return [];
  }
  return readdirSync(SOURCE_DIR, {withFileTypes: true})
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .flatMap((dropId) => readdirSync(join(SOURCE_DIR, dropId))
      .filter((name) => PICTURE.test(name))
      .sort()
      .map((source) => {
        const bytes = readFileSync(join(SOURCE_DIR, dropId, source));
        return {
          bytes,
          dropId,
          path: `images/drops/${dropId}/${hashedName(source, bytes)}`,
          source,
        };
      }));
}

/**
 * The generated TypeScript module's text for a plan.
 * @param {Array<{dropId: string, source: string, path: string}>} plan Plan.
 * @return {string} Module source.
 */
export function manifestSource(plan) {
  const byDrop = new Map();
  for (const {dropId, source, path} of plan) {
    if (!byDrop.has(dropId)) {
      byDrop.set(dropId, []);
    }
    byDrop.get(dropId).push(`    ${JSON.stringify(source)}: ${JSON.stringify(path)},`);
  }
  const drops = [...byDrop.entries()].map(([dropId, lines]) =>
    `  ${JSON.stringify(dropId)}: {\n${lines.join("\n")}\n  },`).join("\n");
  return [
    "/* eslint-disable max-len */",
    "// GENERATED by scripts/build-drop-email-assets.mjs - do not edit by hand.",
    "// Each drop picture's source name mapped to its content-hashed, site-",
    "// relative path, so a changed picture is always a new address.",
    "",
    "export const DROP_ASSETS: Readonly<Record<string, Readonly<Record<string, string>>>> = {",
    drops,
    "};",
    "",
  ].join("\n");
}

/**
 * Publishes every source under its hashed name, removes hashed copies no
 * source produces any more, and rewrites the manifest.
 * @return {string[]} Nothing; problems are thrown.
 */
export function writeDropEmailAssets() {
  const plan = plannedAssets();
  const wanted = new Set(plan.map(({path}) => join(ROOT, "web/public", path)));
  for (const {path, bytes} of plan) {
    const target = join(ROOT, "web/public", path);
    mkdirSync(dirname(target), {recursive: true});
    if (!existsSync(target)) {
      writeFileSync(target, bytes);
    }
  }
  for (const stale of publishedFiles()) {
    if (!wanted.has(stale)) {
      unlinkSync(stale);
    }
  }
  writeFileSync(MANIFEST_PATH, manifestSource(plan));
  return [];
}

/**
 * Every way the published pictures or the manifest disagree with the
 * sources.
 * @return {string[]} Problems; empty when current.
 */
export function checkDropEmailAssets() {
  const plan = plannedAssets();
  const problems = [];
  const wanted = new Set();
  for (const {path, bytes} of plan) {
    const target = join(ROOT, "web/public", path);
    wanted.add(target);
    if (!existsSync(target)) {
      problems.push(`missing published picture ${path}`);
    } else if (!readFileSync(target).equals(bytes)) {
      problems.push(`published picture ${path} differs from its source`);
    }
  }
  for (const published of publishedFiles()) {
    if (!wanted.has(published)) {
      problems.push(`published picture no source produces: ${published.slice(ROOT.length + 1)}`);
    }
  }
  const current = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, "utf8") : "";
  if (current !== manifestSource(plan)) {
    problems.push("functions/src/email/dropAssets.generated.ts is out of date");
  }
  return problems;
}

function publishedFiles() {
  if (!existsSync(PUBLIC_DIR)) {
    return [];
  }
  return readdirSync(PUBLIC_DIR, {withFileTypes: true})
    .filter((entry) => entry.isDirectory())
    .flatMap((entry) => readdirSync(join(PUBLIC_DIR, entry.name))
      .map((name) => join(PUBLIC_DIR, entry.name, name)))
    .filter((path) => PICTURE.test(path));
}

